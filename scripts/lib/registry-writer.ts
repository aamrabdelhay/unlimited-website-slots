import path from "node:path";
import { slotBasePath, slotApiPath } from "../../src/lib/platform-paths";
import type { SlotManifest } from "../../src/lib/manifest";
import {
  atomicWriteFile,
  loadRegisteredSites,
  type RegisteredSite,
} from "./slots-core";

/**
 * Registry generation: discover slots under `sites/`, validate their
 * manifests, then emit the statically-importable TypeScript registry that
 * the Next.js bundler needs, plus JSON indexes for humans and the dashboard.
 */

export interface RegistrySlotIndexEntry extends SlotManifest {
  dirName: string;
  basePath: string;
  apiBasePath: string;
}

export interface RegistryIndex {
  generatedAt: string;
  slots: RegistrySlotIndexEntry[];
}

export interface GenerateRegistryOptions {
  repoRoot: string;
  quiet?: boolean;
  /** Overridable for tests; defaults to <repoRoot>/sites and <repoRoot>/src/generated. */
  sitesDir?: string;
  generatedDir?: string;
  /** Fixed timestamp for deterministic test output. */
  now?: string;
}

export interface GenerateRegistryResult {
  slotIds: number[];
  files: string[];
  index: RegistryIndex;
}

const BANNER = `// ----------------------------------------------------------------------------
// AUTO-GENERATED by scripts/generate-registry.ts — DO NOT EDIT BY HAND.
// Regenerate with: npm run registry:generate
// ----------------------------------------------------------------------------`;

/** Emit deterministic TypeScript source for `src/generated/slot-registry.ts`. */
export function generateRegistryCode(sites: RegisteredSite[]): string {
  const lines: string[] = [BANNER, ""];
  lines.push(`import { slotManifestSchema, type SlotManifest } from "@/lib/manifest";`);
  lines.push(`import type { SiteDefinition } from "@/lib/site-contract";`);
  lines.push("");

  for (const site of sites) {
    const safe = site.dirName.replace(/-/g, "_");
    lines.push(`import { site as site_${safe} } from "../../sites/${site.dirName}/site";`);
    lines.push(`import rawManifest_${safe} from "../../sites/${site.dirName}/manifest.json";`);
  }
  if (sites.length > 0) lines.push("");

  lines.push(`export interface SlotRegistryEntry {`);
  lines.push(`  slotId: number;`);
  lines.push(`  dirName: string;`);
  lines.push(`  basePath: string;`);
  lines.push(`  manifest: SlotManifest;`);
  lines.push(`  site: SiteDefinition;`);
  lines.push(`}`);
  lines.push("");

  for (const site of sites) {
    const safe = site.dirName.replace(/-/g, "_");
    // Validate again at module load so a hand-edited manifest fails loudly.
    lines.push(`const manifest_${safe}: SlotManifest = slotManifestSchema.parse(rawManifest_${safe});`);
  }
  if (sites.length > 0) lines.push("");

  if (sites.length === 0) {
    lines.push(`export const SLOT_ENTRIES: readonly SlotRegistryEntry[] = [];`);
  } else {
    lines.push(`export const SLOT_ENTRIES: readonly SlotRegistryEntry[] = [`);
    for (const site of sites) {
      const safe = site.dirName.replace(/-/g, "_");
      lines.push(
        `  { slotId: ${site.slotId}, dirName: "${site.dirName}", basePath: "${slotBasePath(site.slotId)}", manifest: manifest_${safe}, site: site_${safe} },`,
      );
    }
    lines.push(`];`);
  }
  lines.push("");

  lines.push(
    `export const REGISTERED_SLOT_IDS: readonly number[] = [${sites.map((s) => s.slotId).join(", ")}];`,
  );
  lines.push("");
  lines.push(
    `const entriesById: ReadonlyMap<number, SlotRegistryEntry> = new Map(SLOT_ENTRIES.map((entry) => [entry.slotId, entry]));`,
  );
  lines.push("");
  lines.push(`export function getSlotEntry(slot: number): SlotRegistryEntry | undefined {`);
  lines.push(`  return entriesById.get(slot);`);
  lines.push(`}`);
  lines.push("");
  lines.push(`export function isRegisteredSlot(slot: unknown): slot is number {`);
  lines.push(`  return typeof slot === "number" && entriesById.has(slot);`);
  lines.push(`}`);
  lines.push("");
  return lines.join("\n");
}

/** Build the JSON index consumed by the dashboard and tooling. */
export function buildRegistryIndex(sites: RegisteredSite[], now: string): RegistryIndex {
  return {
    generatedAt: now,
    slots: sites.map((site) => ({
      ...site.manifest,
      dirName: site.dirName,
      basePath: slotBasePath(site.slotId),
      apiBasePath: slotApiPath(site.slotId, "/"),
    })),
  };
}

/** Discover, validate, emit, and verify the generated route table. */
export function generateRegistry(options: GenerateRegistryOptions): GenerateRegistryResult {
  const repoRoot = path.resolve(options.repoRoot);
  const sitesDir = options.sitesDir ?? path.join(repoRoot, "sites");
  const generatedDir = options.generatedDir ?? path.join(repoRoot, "src", "generated");
  const now = options.now ?? new Date().toISOString();

  const { sites, warnings } = loadRegisteredSites(sitesDir);
  for (const warning of warnings) {
    if (!options.quiet) console.warn(`[registry] warning: ${warning}`);
  }

  const code = generateRegistryCode(sites);
  const index = buildRegistryIndex(sites, now);

  const registryFile = path.join(generatedDir, "slot-registry.ts");
  const generatedJsonFile = path.join(generatedDir, "registry.json");
  const rootJsonFile = path.join(repoRoot, "registry.json");

  atomicWriteFile(registryFile, code);
  const json = `${JSON.stringify(index, null, 2)}\n`;
  atomicWriteFile(generatedJsonFile, json);
  atomicWriteFile(rootJsonFile, json);

  // Verification: every discovered slot must appear exactly once in the
  // generated route table, and ids must be unique and ascending.
  const ids = sites.map((s) => s.slotId);
  const unique = new Set(ids);
  if (unique.size !== ids.length) {
    throw new Error("Generated route table verification failed: duplicate slot ids.");
  }
  for (const site of sites) {
    const marker = `slotId: ${site.slotId},`;
    if (!code.includes(marker)) {
      throw new Error(
        `Generated route table verification failed: slot ${site.slotId} missing from ${registryFile}.`,
      );
    }
  }

  return {
    slotIds: ids,
    files: [registryFile, generatedJsonFile, rootJsonFile],
    index,
  };
}
